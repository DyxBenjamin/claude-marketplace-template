/**
 * @file Bundles the installed zod into every vendor/zod.generated.js that plugin code imports; --check fails on drift.
 * @tags zod, vendoring, ci
 * @related plugins/base-plugin/vendor/zod.generated.js, .github/workflows/validate.yml
 */
// Usage: node scripts/vendor-zod.ts [--check]. Bundles the installed zod (schemas, checks, parsing and errors;
// no extra locales or JSON Schema conversion) into one ES module, plus its type declaration, at every
// vendor/zod.generated.js that a TypeScript file under plugins/ imports. --check exits 1 when a copy is
// missing or differs from a fresh bundle, without writing.
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';
import { z } from 'zod';

const root = path.resolve(import.meta.dirname, '..');
const Args = z.union([z.tuple([]), z.tuple([z.literal('--check')])]);
const check = Args.parse(process.argv.slice(2)).length === 1;
const PackageJson = z.looseObject({ version: z.string().min(1) });
const IMPORT = /from\s+['"]((?:\.\.?\/)+(?:[\w-]+\/)*vendor\/zod\.generated\.js)['"]/g;

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.(ts|tsx|mts)$/.test(entry.name)) out.push(full);
  }
  return out;
}

const targets = new Set<string>();
for (const file of walk(path.join(root, 'plugins'))) {
  for (const [, spec] of fs.readFileSync(file, 'utf8').matchAll(IMPORT)) {
    targets.add(path.resolve(path.dirname(file), spec));
  }
}

const { version } = PackageJson.parse(
  JSON.parse(fs.readFileSync(path.join(root, 'node_modules/zod/package.json'), 'utf8')),
);
const license = fs.readFileSync(path.join(root, 'node_modules/zod/LICENSE'), 'utf8').trim().replace(/^/gm, '// ');
const classic = './node_modules/zod/v4/classic';
const ENTRY = `
import * as schemas from '${classic}/schemas.js';
import * as checks from '${classic}/checks.js';
import * as errors from '${classic}/errors.js';
import * as parse from '${classic}/parse.js';
import * as coerce from '${classic}/coerce.js';
import { prettifyError, treeifyError, flattenError } from './node_modules/zod/v4/core/index.js';
export * from '${classic}/schemas.js';
export * from '${classic}/checks.js';
export * from '${classic}/errors.js';
export * from '${classic}/parse.js';
export { coerce, prettifyError, treeifyError, flattenError };
export const z = { ...schemas, ...checks, ...errors, ...parse, coerce, prettifyError, treeifyError, flattenError };
`;
const TYPES = `// @generated by scripts/vendor-zod.ts. Types come from the repo's zod; the bundle holds its schema,
// check, parse and error API.
export * from 'zod';
export { z } from 'zod';
`;
const result = await build({
  stdin: { contents: ENTRY, resolveDir: root, loader: 'js' },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  minify: true,
  legalComments: 'inline',
  write: false,
  banner: { js: `// @generated by scripts/vendor-zod.ts from zod ${version}. Do not edit; run npm run vendor.\n${license}` },
});
const bundle = result.outputFiles[0].text;

let stale = 0;
const files = [...targets].sort().flatMap((t): [string, string][] => [
  [t, bundle],
  [t.replace(/\.js$/, '.d.ts'), TYPES],
]);
for (const [target, content] of files) {
  const rel = path.relative(root, target);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.log(`stale ${rel}; run npm run vendor`);
    stale++;
    continue;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content);
  console.log(`wrote ${rel}`);
}
process.exit(stale ? 1 : 0);
